//! Check one worker in its own accounting frame. Publication transfers captures;
//! analysis retains an independent ordered body, not an eagerly completed call
//! in the parent's history. Normal results remain behind the completion record.

use super::super::{
    accounting::Accounting,
    analysis::Analysis,
    contracts,
    elements::References,
    lifetime::{Storage, Value},
    model::{unit, unsupported},
    summary::BodyEffects,
};
use super::{WorkerId, inputs};
use crate::{ast::*, messages::Span};
use std::sync::Arc;

/// Remaining capture owners destroyed together at a source exit. The map
/// identifies members, not their destruction order. Exclusion proofs must cover
/// every source-permitted ordering of this implicit group.
struct CaptureCleanup {
    /// Source return or reachable fallthrough whose captures are ending.
    exit: Span,
    /// Remaining separately owned descendants, including shared root links.
    owners: std::collections::BTreeMap<super::super::heap::OwnerSlot, super::super::heap::Owner>,
}

/// Structurally checked effects with outstanding Verus/global proof obligations.
/// Only body analysis creates this object. It is not proof of panic freedom,
/// successful native join, or a total concurrent memory bound.
pub(in super::super) struct Execution {
    /// One fixed publication occurrence; never a thread population count.
    pub(super) actor: WorkerId,
    /// Original concrete closure type identity used by compiler evidence.
    pub(in super::super) definition: usize,
    /// Full entry descriptor, including construction epoch, original allocation
    /// identities and source/compiler capture paths. It survives collection.
    pub(super) entry: super::body::Entry,
    pub(super) publication: super::states::Publication,
    /// Immutable charge observations at publication, before body mutations.
    pub(super) initial: Accounting,
    /// Capture-to-source substitutions and immutable construction observations.
    pub(super) inputs: Vec<inputs::Input>,
    /// Ordered source control flow and accepted ownership operations.
    pub(super) effects: Arc<BodyEffects>,
    /// Existing parametric ownership interface, including loop-derived effects.
    pub(super) transfer: Option<super::super::transfer::Template>,
    /// Runtime child ownership requires a representable parametric template.
    pub(super) transfer_required: bool,
    capture_cleanup: Vec<CaptureCleanup>,
    /// Original body graph, with its own local/instance/acquisition namespace.
    pub(super) synchronization: super::super::synchronization::flow::Graph,
    /// Source closure preconditions, still proved at the actual spawn call.
    pub(super) requirements: Exprs,
    /// Byte inequalities generated by body operations and checkpoints.
    pub(super) obligations: Vec<super::super::accounting::Obligation>,
    /// Additional body safety obligations such as reserved-capacity checks.
    pub(super) checks: Vec<(Span, Expr)>,
    /// Independent actor history; it is never added to the caller as a call peak.
    pub(super) report: super::super::accounting::MemoryReport,
    /// Actual normal result after every source return's capture cleanup.
    pub(super) result: Storage,
    /// All storage retained by completion, including newly created shared backing.
    pub(super) retained: Accounting,
    /// Entry-to-exit strong-reference relation and newly owned roots.
    pub(super) shared: super::super::shared::SharedRoots,
}

impl Execution {
    pub(in super::super) fn shared_checkpoints(
        &self,
    ) -> &[super::super::shared::phases::Checkpoint] {
        &self.effects.ownership.shared_checkpoints
    }
}

impl Analysis<'_> {
    /// Keep the missing global proof explicit after checking actual source
    /// effects. Structurally valid local executions do not establish an envelope
    /// over simultaneous worker states or synchronization containment.
    pub(in super::super) fn check_worker_domain(
        &self,
        span: &Span,
    ) -> Result<Option<VirErr>, VirErr> {
        if self.growth.worker_executions.is_empty() {
            return Ok(None);
        }
        // Every worker in this domain has been collected before this check.
        // Its imported reference relation has therefore been composed back into
        // the coordinator. Remaining aliases must belong to the actual result
        // or to canonically retained payloads, never to a discarded body view.
        self.heap.shared.check_result(self.result_owner.as_ref(), References::None, span)?;
        for (actor, execution) in &self.growth.worker_executions {
            if *actor != execution.actor {
                return Err(unsupported(
                    span,
                    "a worker summary substituted for a different actor",
                ));
            }
            execution.effects.validate(self.summaries)?;
            let owned = execution.entry.captures.owned_slots(self.layouts);
            for cleanup in &execution.capture_cleanup {
                if !cleanup.owners.keys().all(|slot| owned.contains(slot)) {
                    return Err(unsupported(
                        &cleanup.exit,
                        "worker cleanup outside its captured ownership",
                    ));
                }
            }
            if execution.transfer_required && execution.transfer.is_none() {
                return Err(unsupported(
                    span,
                    "worker effects without their required ownership template",
                ));
            }
            if !matches!(&*execution.entry.definition.typ, TypX::AnonymousClosure(_, _, _, id) if *id == execution.definition)
                || execution.synchronization.arguments != 1
                || execution
                    .requirements
                    .iter()
                    .any(|condition| !matches!(&*condition.typ, TypX::Bool))
                || execution.inputs.iter().any(|input| {
                    input
                        .scalar
                        .as_ref()
                        .is_some_and(|value| !crate::ast_util::types_equal(&value.typ, &input.typ))
                        || input.projections.iter().any(|(path, value)| {
                            path.is_empty() || !super::super::contracts::scalar(&value.typ)
                        })
                })
            {
                return Err(unsupported(span, "inconsistent worker entry proof bindings"));
            }
        }
        Ok(Some(unsupported(
            span,
            "concurrent contracts before concurrent lifetime accounting is available: checked worker effects still require global lifetime and interference proofs",
        )))
    }

    /// These are necessary local inequalities, not the simultaneous envelope.
    /// Prove them at the original worker operations under the original closure
    /// preconditions. The deferred global diagnostic still prevents acceptance.
    pub(in super::super) fn worker_obligations(&mut self) -> Result<(), VirErr> {
        for worker in self.growth.worker_executions.values() {
            self.obligations.extend(worker.obligations.iter().cloned());
            self.checks.extend(worker.checks.iter().cloned());
        }
        self.state_obligations()
    }

    pub(super) fn analyze_worker(&mut self, actor: WorkerId, span: &Span) -> Result<(), VirErr> {
        let mut entry = self.heap.workers.enter(actor, span)?;
        let entry_descriptor = entry.clone();
        let definition = entry.definition.clone();
        let TypX::AnonymousClosure(_, result_type, _, id) = &*definition.typ else {
            return Err(unsupported(span, "worker analysis without a concrete definition"));
        };
        let closure = &self.concurrency.closures[id];
        let ExprX::NonSpecClosure { body, requires, .. } = &definition.x else {
            return Err(unsupported(span, "worker analysis without an executable source body"));
        };
        let inputs = inputs::bind(
            closure,
            entry.storage.value.environment.unwrap(),
            &self.growth.environments,
            self.layouts,
            span,
        )?;
        let body = inputs::body(body, &inputs)?;
        let signature =
            inputs::signature(&definition, body.clone(), &inputs, closure, self.functions)?;
        super::super::control::validate(&body, &self.var_modes)?;
        let at_fork = self.storage.live_expression(span);
        let mut storage = self.storage.take_storage(&entry.storage, &self.growth, span)?;
        let (body_workers, tags) =
            self.heap.workers.body_scope(actor, entry.storage.owner.as_ref(), span)?;
        for tag in tags {
            // Moving a join handle transfers responsibility for its completion
            // record. It neither runs the target nor allocates another tag.
            let completion = Storage {
                typ: crate::ast_util::unit_typ(),
                value: Value {
                    bytes: verus_meter_model::completion_bytes(0).unwrap(),
                    ids: [tag].into(),
                    origins: [tag].into(),
                    ..Value::unit()
                },
                owner: None,
            };
            storage.receive_storage(
                self.storage.take_storage(&completion, &self.growth, span)?,
                span,
            )?;
        }
        let publication = self.publication_state(span, actor, at_fork)?;
        let initial = storage.clone();
        // The full-drain rule applies to coordinator publications whose result
        // cannot carry a handle or alias out of the collecting worker.
        let collection_entries = if self.current_worker.is_none()
            && (unit(result_type) || contracts::scalar(result_type))
        {
            self.capture_collection_claims(span, &entry, &inputs)
        } else {
            Default::default()
        };
        let declarations = self.growth.declarations.len();
        // Enclosing loop coordinates belong to the actor's identity, not its
        // local control flow. A child body begins a separate reusable frame.
        let parent_loop_depth = self.growth.loop_depth;
        let parent_loop_regions = std::mem::take(&mut self.growth.loop_regions);
        let parent_loop_counters = std::mem::take(&mut self.growth.loop_counters);
        self.growth.loop_depth = 0;
        let mut worker = Analysis {
            worker_inputs: inputs.clone(),
            capture_views: inputs.iter().map(|input| input.name.clone()).collect(),
            evaluations: Default::default(),
            concurrency: self.concurrency,
            current_worker: Some(actor),
            flow: Default::default(),
            transitions: Default::default(),
            slots: Default::default(),
            produced: None,
            summaries: self.summaries,
            result_owner: None,
            budgets: self.budgets,
            layouts: self.layouts,
            functions: self.functions,
            var_modes: self.var_modes.clone(),
            storage,
            calls: vec![],
            checkpoints: vec![],
            stable_scalars: Default::default(),
            heap: super::super::heap::Heap::default(),
            obligations: vec![],
            checks: vec![],
            input_paths: vec![],
            growth: std::mem::take(&mut self.growth),
            bound: self.bound.clone(),
        };
        worker.transitions.collection_claims = collection_entries;
        worker.heap.shared = entry.shared.clone();
        worker.heap.workers = body_workers;
        worker.growth.runtime_classification |=
            super::super::transfer::required(&signature, worker.layouts)?;
        let mut mutable = std::collections::HashSet::new();
        crate::ast_visitor::expr_visitor_check(&body, &mut |_, value| {
            let place = match &value.x {
                ExprX::Assign { place, .. }
                | ExprX::BorrowMut(place)
                | ExprX::TwoPhaseBorrowMut(place) => Some(place),
                _ => None,
            };
            if let Some(place) = place
                && let Some((name, _)) = super::super::paths::place(place, &place.typ)
            {
                mutable.insert(name);
            }
            Ok::<(), VirErr>(())
        })?;
        for (index, input) in inputs.iter().enumerate() {
            if entry.captures.source_path(&input.source) != Some(vec![input.slot.clone()]) {
                return Err(unsupported(
                    span,
                    "worker input substituted for a different capture path",
                ));
            }
            worker.var_modes.insert(input.name.clone(), Mode::Exec);
            // This is a view: the enclosing environment owns the inline charge.
            worker.slots.insert(
                input.name.clone(),
                Value {
                    bytes: worker.layouts.size(&input.typ, span)?,
                    environment: input.environment,
                    ..Value::unit()
                },
            );
            if super::super::contracts::scalar(&input.typ) && !mutable.contains(&input.name) {
                worker.stable_scalars.insert(input.name.clone());
            }
            if worker.layouts.owner(&input.typ) {
                let mut owner = entry
                    .storage
                    .owner
                    .as_mut()
                    .and_then(|owner| owner.children.remove(&input.slot))
                    .ok_or_else(|| unsupported(span, "worker entry missing a captured owner"))?;
                worker.enter_worker_owner(&mut owner, &body.span)?;
                if owner.references() == References::WorkerOccurrences && owner.elements.is_some() {
                    let memory = worker.snapshot_owner_metadata(&body.span, &owner);
                    worker.transitions.captured_populations.insert(index, memory);
                } else if let Some(handle) = &mut owner.worker
                    && let Some(publication) = &handle.publication
                    && worker.growth.worker_executions[&handle.actor]
                        .result
                        .owner
                        .as_ref()
                        .is_some_and(|result| result.references() == References::WorkerOccurrences)
                {
                    // The captured handle's checked publication describes the population
                    // obtained by joining it. Keep an entry value for loop induction;
                    // the publishing trace can specialize it to the actual operand.
                    let snapshot = worker.metadata_local(
                        &body.span,
                        "captured_publication",
                        publication.clone(),
                    );
                    handle.publication = Some(snapshot.clone());
                    worker.transitions.captured_populations.insert(index, snapshot);
                }
                worker.heap.owners.insert(input.name.clone(), owner);
            }
        }
        let result = worker.produce(&body)?;
        // Each source return must keep its result separate while captures end.
        // An implicit capture group has no promised release order for exclusion.
        let mut cleanup_error = None;
        let mut capture_cleanup = Vec::new();
        worker.cleanup_edges(0, |worker, exit| {
            let exit = exit.unwrap_or(&body.span).clone();
            if worker.flow.reachable {
                capture_cleanup.push(CaptureCleanup {
                    exit,
                    owners: inputs
                        .iter()
                        .filter_map(|input| {
                            worker
                                .heap
                                .owners
                                .get(&input.name)
                                .map(|owner| (input.slot.clone(), owner.clone()))
                        })
                        .collect(),
                });
            }
            let mut cleanup = entry.clone();
            for input in &inputs {
                if let Some(owner) = worker.heap.owners.remove(&input.name) {
                    if cleanup.invocation.cleans_up_after_body() {
                        cleanup
                            .storage
                            .owner
                            .as_mut()
                            .expect("owned capture environment")
                            .children
                            .insert(input.slot.clone(), owner);
                    } else {
                        worker.release_owner(owner, span);
                    }
                }
                worker.slots.remove(&input.name);
            }
            match cleanup.into_return_cleanup(worker.layouts) {
                Ok(storage) => {
                    if let Some(owner) = storage.owner {
                        worker.release_owner(owner, span);
                    }
                    worker.release_value(storage.value, span);
                }
                Err(error) => cleanup_error = Some(error),
            }
        });
        if let Some(error) = cleanup_error {
            return Err(error);
        }
        let result = worker.finish_returns(span, result)?;
        if !worker.heap.temporaries.is_empty() || !worker.evaluations.is_empty() {
            return Err(unsupported(span, "unclosed worker receiver-temporary scopes"));
        }
        worker.heap.workers.check_closed(span)?;
        if !worker.heap.owners.is_empty() || !worker.slots.is_empty() {
            return Err(unsupported(span, "worker completion with unaccounted local storage"));
        }
        worker.check_checkpoints()?;
        let transfer_required = super::super::transfer::requires_summary(
            &signature,
            worker.layouts,
            &worker.transitions,
            worker.summaries,
        )?;
        let inferred = super::super::transfer::summarize(
            &signature,
            worker.layouts,
            worker.functions,
            worker.summaries,
            &worker.var_modes,
            &worker.transitions,
        )?;
        if let Some(inferred) = &inferred {
            worker.apply_transfer_evidence(inferred)?;
        }
        let result =
            Storage { typ: result_type.clone(), value: result, owner: worker.result_owner.take() };
        // A retained occurrence carries its own join obligation in the result.
        // Indexed shared claims must be reconciled in their publishing domain.
        // Finite output links still have to account for this body's aliases.
        worker.heap.shared.check_result(
            result.owner.as_ref(),
            References::WorkerOccurrences,
            span,
        )?;
        let mut retained = worker.storage.take_storage(&result, &worker.growth, span)?;
        let backing = Storage {
            typ: crate::ast_util::unit_typ(),
            value: Value::unit(),
            owner: Some(worker.heap.shared.owned_backing()),
        };
        retained
            .receive_storage(worker.storage.take_storage(&backing, &worker.growth, span)?, span)?;
        worker.storage.check_transferred(span)?;
        let report = worker.storage.finish_conditional();
        let declarations = worker.growth.declarations.split_off(declarations);
        if !declarations.is_empty() {
            worker.growth.before.entry(body.span.id).or_default().splice(0..0, declarations);
        }
        let execution = Arc::new(Execution {
            actor,
            definition: *id,
            inputs,
            entry: entry_descriptor,
            publication,
            initial,
            effects: Arc::new(BodyEffects {
                body,
                ownership: worker.transitions,
                calls: worker.calls,
            }),
            transfer: inferred.map(|inferred| inferred.template),
            transfer_required,
            capture_cleanup,
            synchronization: closure.body.clone(),
            requirements: requires.clone(),
            obligations: worker.obligations,
            checks: worker.checks,
            report,
            result,
            retained,
            shared: worker.heap.shared,
        });
        self.growth = worker.growth;
        self.growth.loop_depth = parent_loop_depth;
        self.growth.loop_regions = parent_loop_regions;
        self.growth.loop_counters = parent_loop_counters;
        self.growth.worker_executions.insert(actor, execution.clone());
        self.heap.workers.records.get_mut(&actor).expect("live checked worker").execution =
            Some(execution);
        Ok(())
    }
}
